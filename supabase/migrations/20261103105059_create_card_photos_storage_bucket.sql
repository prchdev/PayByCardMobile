/*
# Create card-photos storage bucket

1. New Storage Bucket
- `card-photos` (private bucket) for storing front/back photos of user credit/debit cards
- Photos contain sensitive card info (masked first 12 digits, last 4 digits, name) so bucket is private
- Signed URLs are generated by edge functions for temporary access

2. Security
- Bucket is private (not public)
- RLS enabled on storage.objects for the card-photos bucket
- Only authenticated users can upload/read their own card photos (path starts with their user_id)
*/

INSERT INTO storage.buckets (id, name, public)
VALUES ('card-photos', 'card-photos', false)
ON CONFLICT (id) DO NOTHING;

-- Allow authenticated users to upload to their own folder
DROP POLICY IF EXISTS "Users can upload own card photos" ON storage.objects;
CREATE POLICY "Users can upload own card photos"
ON storage.objects FOR INSERT
TO authenticated
WITH CHECK (bucket_id = 'card-photos' AND (storage.foldername(name))[1] = auth.uid()::text);

-- Allow authenticated users to read their own card photos
DROP POLICY IF EXISTS "Users can read own card photos" ON storage.objects;
CREATE POLICY "Users can read own card photos"
ON storage.objects FOR SELECT
TO authenticated
USING (bucket_id = 'card-photos' AND (storage.foldername(name))[1] = auth.uid()::text);

-- Allow authenticated users to update/overwrite their own card photos
DROP POLICY IF EXISTS "Users can update own card photos" ON storage.objects;
CREATE POLICY "Users can update own card photos"
ON storage.objects FOR UPDATE
TO authenticated
USING (bucket_id = 'card-photos' AND (storage.foldername(name))[1] = auth.uid()::text)
WITH CHECK (bucket_id = 'card-photos' AND (storage.foldername(name))[1] = auth.uid()::text);

-- Allow service_role full access (edge functions use this)
DROP POLICY IF EXISTS "Service role can manage card photos" ON storage.objects;
CREATE POLICY "Service role can manage card photos"
ON storage.objects FOR ALL
TO service_role
USING (bucket_id = 'card-photos')
WITH CHECK (bucket_id = 'card-photos');
